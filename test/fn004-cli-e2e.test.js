test('6F actual TTY no-op Apply keeps all canonical files and high-water unchanged',{timeout:900000},async t=>{
 const f=await cliFixture(t,{noop:true});
 const identities=async()=>Promise.all(CANONICAL_TABLES.map(async table=>{
  const stat=await fs.stat(join(f.root,table.path),{bigint:true});return {path:table.path,inode:String(stat.ino),mtime:String(stat.mtimeNs)};
 }));
 const before=await identities(),snapshot=(await readCanonicalSnapshot(f.root)).manifest;
 const output=await tty(f.root,f.args);const dto=must(output);
 assert.equal(dto.readiness,'initialized');assert.equal(dto.canonical_effect,'applied');
 assert.deepEqual((await readCanonicalSnapshot(f.root)).manifest,snapshot);assert.deepEqual(await identities(),before);
 const state=JSON.parse(await fs.readFile(join(f.root,'staging/fn004-state.json')));
 assert.deepEqual(state.high_water_marks,f.state.high_water_marks);assert.deepEqual(state.allocation_events,[]);
 assert.equal(state.pending_transaction,null);
 const applyId=dto.data.response.result.apply_id;
 const history=must(await cli(f.root,['history','show',applyId])).data;
 assert.deepEqual(history.payload.id_mappings,[]);assert.ok(history.payload.results.some(r=>r.classification==='no_op'));
 assert.equal(history.payload.results.some(r=>r.classification==='insert'),false);
 assert.ok(output.stderr.includes('"changed_csvs": []'));assert.ok(output.stderr.includes('"no_op": ['));
});
