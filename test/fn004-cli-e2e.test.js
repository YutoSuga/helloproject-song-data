test('6F actual CLI Decision/Plan/TTY Apply/result/History end-to-end and readonly terminal restart',{timeout:1800000},async t=>{
 const f=await cliFixture(t,{newEntities:true});
 await fs.writeFile(join(f.root,'staging/decisions.json'),JSON.stringify({schema_version:1,revisions:[]}));
 for(const path of ['staging/apply-plans','staging/apply-approvals'])await fs.rm(join(f.root,path),{recursive:true});
 const candidate=f.decision.scope.candidate_ids[0];
 const before=await evidenceHashes(f.root);
 const template=must(await cli(f.root,['decision','template','--candidate',candidate])).data;
 assert.deepEqual(await evidenceHashes(f.root),before);
 template.content=decisionContent(f.decision);
 const input=join(f.root,'draft-input.json');await fs.writeFile(input,JSON.stringify(template));
 const draft=must(await cli(f.root,['decision','import','--input',input])).data.revision;
 assert.notEqual(draft.decision_id,f.decision.decision_id);assert.equal(draft.revision,1);assert.match(draft.actor.id,/^local:/);
 const retry=must(await cli(f.root,['decision','import','--input',input])).data;assert.equal(retry.replayed,true);assert.deepEqual(retry.revision,draft);
 const saved=await evidenceHashes(f.root);
 must(await cli(f.root,['decision','show',draft.decision_id]));
 assert.equal(must(await cli(f.root,['decision','validate',draft.decision_id,'--revision','1'])).data.confirmable,true);
 assert.deepEqual(await evidenceHashes(f.root),saved);
 must(await cli(f.root,['decision','confirm',draft.decision_id,'--revision','1','--expect-head','f'.repeat(64)]),8);
 const confirmed=must(await cli(f.root,['decision','confirm',draft.decision_id,'--revision','1','--expect-head',draft.content_hash])).data.revision;
 const plan=must(await cli(f.root,['plan','create','--decision',confirmed.decision_id,'--revision',String(confirmed.revision),'--expect-decision-hash',confirmed.content_hash])).data;
 assert.equal(plan.payload.applicability.applicable,true);
 const prepared=await evidenceHashes(f.root);
 must(await cli(f.root,['plan','show',plan.plan_id]));must(await cli(f.root,['plan','check',plan.plan_id]));
 assert.deepEqual(await evidenceHashes(f.root),prepared);
 const args=['apply','--plan',plan.plan_id,'--expect-plan-hash',plan.plan_hash];
 must(await cli(f.root,args),3); // pipe cannot forge interactive approval
 const cancelled=await tty(f.root,args,{answer:'n\n'});must(cancelled,10);
 assert.equal(cancelled.answered,true);assert.deepEqual(await evidenceHashes(f.root),prepared);
 const ci=await tty(f.root,args,{env:{CI:'true'}});must(ci,3);assert.equal(ci.answered,false);
 const applied=await tty(f.root,args);const dto=must(applied);
 assert.equal(applied.answered,true);assert.equal(dto.canonical_effect,'applied');assert.equal(dto.readiness,'initialized');
 assert.equal(dto.data.response.result!==null,true);
 const r=dto.data.response.artifact.receipt,after=await evidenceHashes(f.root);
 assert.ok(applied.stderr.includes('Accepted Request: '+r.request_id));
 const result=must(await cli(f.root,['result','--request',r.request_id]));assert.equal(result.data.response.result.apply_id,r.apply_id);
 must(await cli(f.root,['history','show',r.apply_id]));
 assert.equal(must(await cli(f.root,['status'])).readiness,'initialized');
 const observation=must(await cli(f.root,['recovery','inspect','--request',r.request_id])).data;
 assert.deepEqual(observation.allowed_actions,[]);
 must(await cli(f.root,['recovery','run','--transaction',r.transaction_id,'--expect-state-hash',observation.observed_state_hash,'--action','rollback']),6);
 assert.deepEqual(await evidenceHashes(f.root),after);
 assert.equal((await readCanonicalSnapshot(f.root)).validation.ok,true);
 assert.equal((await fs.readdir(join(f.root,'staging/apply-history'))).length,1);
 const state=JSON.parse(await fs.readFile(join(f.root,'staging/fn004-state.json')));
 assert.equal(state.pending_transaction,null);
 assert.deepEqual([...new Set(state.allocation_events.map(e=>e.transaction_id))],[r.transaction_id]);
 assert.equal(new Set(state.allocation_events.map(e=>e.namespace)).size,state.allocation_events.length);
 assert.equal(state.allocation_events.reduce((n,e)=>n+e.last-e.first+1,0),plan.payload.planned_id_mappings.length);
 for(const mapping of plan.payload.planned_id_mappings){const event=state.allocation_events.find(e=>e.namespace===mapping.namespace);assert.ok(event&&Number(mapping.planned_id.slice(1))>=event.first&&Number(mapping.planned_id.slice(1))<=event.last);}
 const request=JSON.parse(await fs.readFile(join(f.root,`staging/apply-requests/${r.request_id}.json`)));
 assert.deepEqual(request.receipt,r);
});

test('6F actual CLI bootstrap audit/declaration/TTY confirmation and incomplete state',{timeout:900000},async t=>{
 const f=await cliFixture(t);
 await fs.rm(join(f.root,'staging'),{recursive:true});
 const declaration={schema_version:1,namespaces:f.state.high_water_marks,statement:DECLARATION_STATEMENT,evidence:[{kind:'human_note',value:'Isolated fixture external audit'}]};
 const path=join(f.root,'declaration.json');await fs.writeFile(path,JSON.stringify(declaration));
 assert.equal(must(await cli(f.root,['status'])).data.status,'BOOTSTRAP_REQUIRED');
 must(await cli(f.root,['init','--check']),2);
 const check=must(await cli(f.root,['init','--check','--external-declaration',path])).data;
 assert.equal(check.readiness,'initializable');assert.match(check.audit_hash,/^[0-9a-f]{64}$/);
 const args=['init','--external-declaration',path,'--expect-audit-hash',check.audit_hash];
 must(await cli(f.root,args),3);
 must(await tty(f.root,args,{answer:'n\n'}),10);
 await assert.rejects(fs.stat(join(f.root,'staging/fn004-state.json')),{code:'ENOENT'});
 must(await tty(f.root,args));
 assert.equal(must(await cli(f.root,['status'])).readiness,'initialized');
 const marker=JSON.parse(await fs.readFile(join(f.root,'staging/fn004-bootstrap.json'))),beforeRetry=await evidenceHashes(f.root);
 must(await tty(f.root,args,{answer:'n\n'}),10);
 const repeated=must(await tty(f.root,args));
 assert.equal(repeated.data.code,'BOOTSTRAP_ALREADY_INITIALIZED');
 assert.equal(repeated.data.repository_instance_id,marker.payload.repository_instance_id);
 assert.equal(repeated.data.bootstrap_hash,marker.bootstrap_hash);
 assert.deepEqual(await evidenceHashes(f.root),beforeRetry);
 const bytes=await fs.readFile(join(f.root,'staging/fn004-state.json'));
 await fs.unlink(join(f.root,'staging/fn004-bootstrap.json'));
 assert.equal(must(await cli(f.root,['status'])).data.status,'BOOTSTRAP_INCOMPLETE');
 must(await cli(f.root,['init','--check','--external-declaration',path]),12);
 const blocked=must(await tty(f.root,args),12);assert.equal(blocked.error.code,'BOOTSTRAP_INCOMPLETE');
 assert.deepEqual(await fs.readFile(join(f.root,'staging/fn004-state.json')),bytes);
});

