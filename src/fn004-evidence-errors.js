export function validateDiagnostics(values) {
  ordered(values, value => value.code);
  for (const value of values) { closed(value, ['code']); check(RECOVERY_CODES.includes(value.code), 'Unknown Recovery diagnostic code'); }
}

export const PERSISTENCE_PHASES = Object.freeze(['encode', 'ensure_directory', 'temp_create', 'temp_write',
  'file_sync', 'temp_verify', 'publish', 'directory_sync', 'temp_cleanup']);

export function validateErrorEvidence(value) {
  closed(value, ['code', 'operation', 'path', 'persistence_phase', 'published', 'io_code']);
  check(RECOVERY_CODES.includes(value.code) && ['accept', 'prepare', 'consume', 'replace', 'validate',
    'decide', 'history', 'state', 'rollback', 'recover', 'cleanup'].includes(value.operation) &&
    (value.persistence_phase === null || PERSISTENCE_PHASES.includes(value.persistence_phase)) &&
    (value.published === null || typeof value.published === 'boolean') &&
    (value.io_code === null || nonempty(value.io_code)), 'Invalid typed error evidence');
  if (value.path !== null) observedPath(value.path);
}
